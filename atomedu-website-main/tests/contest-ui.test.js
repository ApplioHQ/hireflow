import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = (file) => readFileSync(resolve(root, file), 'utf8');

test('contest begins with the winner and explains graph export, schedule, consent, and archive', () => {
  const page = read('art-contest.html');
  assert.ok(page.indexOf('class="winner-section') < page.indexOf('class="contest-hero'), 'winner banner precedes the intro');
  assert.match(page, /id="winner-image"/);
  assert.match(page, /id="winner-name"/);
  assert.match(page, /Save PNG/);
  assert.match(page, /Desmos graphs, art from other software/);
  for (const criterion of ['Beauty', 'Creativity', 'Complexity']) assert.match(page, new RegExp(`<h4>${criterion}</h4>`));
  assert.equal((page.match(/UP TO 10 POINTS/g) || []).length, 3);
  assert.match(page, /second-highest scorer is the runner-up/);
  assert.match(page, /If any totals tie, the judges must review and resolve the scores before results can be published/);
  assert.match(page, /id="runner-image"/);
  assert.match(page, /id="runner-name"/);
  assert.ok(page.indexOf('id="runner-image"') > page.indexOf('class="art-sheet"'));
  assert.doesNotMatch(page, /class="runner-card"/);
  assert.match(read('art-contest.js'), /renderRunnerUp/);
  assert.match(page, /id="terms-accepted"/);
  assert.match(page, /id="display-consent"/);
  assert.match(page, /Confirm and submit/);
  assert.match(page, /id="archive-grid"/);
  assert.match(page, /00:00 next day/);
  assert.match(page, /23:00 same day/);
  assert.match(page, /02:30 next day/);
  assert.match(page, /03:30 next day/);
  assert.doesNotMatch(page + read('art-contest.js'), /[—–·]/);
  assert.ok(page.indexOf('contest-config.js') < page.indexOf('art-contest.js'));
});

test('judging stays server-backed and neither public page embeds an admin password', () => {
  const page = read('judging.html');
  const publicScript = read('art-contest.js');
  const judgeScript = read('judging.js');
  assert.match(page, /name="robots" content="noindex,nofollow"/);
  assert.match(page, /id="judge-password"/);
  assert.match(page, /id="contest-date"/);
  assert.ok(page.indexOf('contest-config.js') < page.indexOf('judging.js'));
  assert.match(judgeScript, /Bearer/);
  assert.match(judgeScript, /createObjectURL/);
  assert.match(page, /Score Beauty, Creativity, and Complexity from 0 to 10/);
  assert.match(judgeScript, /Save scores/);
  assert.match(judgeScript, /month: 'short', day: 'numeric' \}\)\.format\(date\)/);
  assert.doesNotMatch(judgeScript.match(/function formatSubmittedDate\(value\) \{[\s\S]*?\n  \}/)?.[0] || '', /hour:|minute:|timeZoneName:/);
  assert.match(page, /id="submit-scores"/);
  assert.match(page, /id="results-dialog"/);
  assert.match(page, /id="preview-winner-image"/);
  assert.match(page, /id="preview-runner-image"/);
  assert.match(page, /Confirm submission/);
  assert.doesNotMatch(page + judgeScript, /Select winner/);
  assert.match(judgeScript, /expectedRunnerUpId/);
  assert.match(judgeScript, /actions\.append\(total, remove\)/);
  assert.match(judgeScript, /tiedTotals\(currentEntries\)/);
  assert.match(judgeScript, /tiedTotals\(latest\.submissions\)/);
  assert.match(read('judging.css'), /\.score-total\.is-tied \{ color: #a12424;/);
  assert.match(page, /Resolve every tied total before submitting/);
  assert.doesNotMatch(page + judgeScript, /[—–·]/);
  assert.doesNotMatch(publicScript + judgeScript + page, /(?:password\s*[:=]\s*['"]admin['"]|Basic\s+YWRtaW4)/i);
  assert.match(read('contest-config.js'), /ATOM_CONTEST_API_BASE = 'https:\/\/atom-contest-api\.archimedes-api1\.workers\.dev\/api\/art-contest'/);
  assert.doesNotMatch(read('contest-config.js'), /JUDGING_PASSWORD|SESSION_SECRET|admin/i);
  assert.match(read('art-contest.html'), /contest-config\.js\?v=2026-11-15/);
  assert.match(page, /contest-config\.js\?v=2026-11-15/);
});
